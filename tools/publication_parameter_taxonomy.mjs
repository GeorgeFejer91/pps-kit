/**
 * Proposed paper-dependent target parameter taxonomy for publication recreation.
 *
 * This is deliberately finer-grained than the current 25-field literature
 * audit and the 15/19-field profile-recreation gate. Each leaf is intended to
 * receive its own source-review status. These are target requirements, not
 * claims about fields accepted by the current serializer. Repeating entities
 * are represented as arrays in evidence/value stores, not by duplicating
 * semantic columns.
 */

