function provisionalRoutingHint(groupDefinition, key) {
  if (STRUCTURAL_GAP_KEYS.has(key)) return "unsupported_structural_gap";
  if (FIXED_POLICY_KEYS.has(key)) return "fixed_policy_not_configurable";
  if (DERIVED_KEYS.has(key)) return "derived_materialized";
  if (FREEFORM_KEYS.has(key)) return "freeform_metadata_only";
  if (FIRST_CLASS_KEYS.has(key)) return "first_class_gui";
  return groupDefinition.defaultSupport;
}

function inferredUnit(key) {
  if (key.endsWith("_ms")) return "ms";
  if (key.endsWith("_s")) return "s";
  if (key.endsWith("_hz")) return "Hz";
  if (key.endsWith("_mps")) return "m/s";
  if (key.endsWith("_cm_s")) return "cm/s";
  if (key.endsWith("_cm")) return "cm";
  if (key.endsWith("_m")) return "m";
  if (key.endsWith("_deg")) return "degree";
  if (key.endsWith("_dbfs")) return "dBFS";
  if (key.endsWith("_db")) return "dB";
  if (key.endsWith("_percent")) return "%";
  return "";
}

function inferredShape(key, repeatableEntity) {
  if (
    key.includes("_labels") ||
    key.includes("_values") ||
    key.includes("_positions") ||
    key.includes("_factors") ||
    key.includes("_criteria") ||
    key.includes("_terms") ||
    key.includes("_set") ||
    key.includes("_mapping") ||
    key.includes("_sequence") ||
    key.includes("_overrides") ||
    key.includes("_membership") ||
    key.includes("_forms")
  ) {
    return "array_or_mapping";
  }
  if (
    key.endsWith("_enabled") ||
    key.endsWith("_required") ||
    key.startsWith("include_") ||
    key.startsWith("pair_") ||
    key.startsWith("repeat_") ||
    key.startsWith("distribute_") ||
    key.startsWith("catch_crosses_") ||
    key.startsWith("baseline_crosses_") ||
    key.startsWith("auditory_only_crosses_")
  ) {
    return "boolean";
  }
  if (inferredUnit(key) || key.endsWith("_count") || key.endsWith("_n") || key === "alpha") {
    return repeatableEntity ? "number_or_number_array" : "number";
  }
  return repeatableEntity ? "scalar_or_array" : "scalar";
}

